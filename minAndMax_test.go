package decimal

import "testing"

func TestMinAndMax(t *testing.T) {
	tf := func(min, max any, arr []any) {
		t.Helper()
		assertEq(t, New(max).ValueOf(), Default.Max(arr...).ValueOf())
		assertEq(t, New(min).ValueOf(), Default.Min(arr...).ValueOf())
	}

	setCfg(20, 4, -7, 21, 9e15, -9e15, 1, false)

	tf(nan(), nan(), []any{nan()})
	tf(nan(), nan(), []any{-2.0, 0.0, -1.0, nan()})
	tf(nan(), nan(), []any{-2.0, nan(), 0.0, -1.0})
	tf(nan(), nan(), []any{nan(), -2.0, 0.0, -1.0})
	tf(nan(), nan(), []any{nan(), -2.0, 0.0, -1.0})
	tf(nan(), nan(), []any{-2.0, 0.0, -1.0, New(nan())})
	tf(nan(), nan(), []any{-2.0, 0.0, -1.0, New(nan())})
	tf(nan(), nan(), []any{inf(1), -2.0, "NaN", 0.0, -1.0, inf(-1)})
	tf(nan(), nan(), []any{"NaN", inf(1), -2.0, 0.0, -1.0, inf(-1)})
	tf(nan(), nan(), []any{inf(1), -2.0, nan(), 0.0, -1.0, inf(-1)})

	tf(0.0, 0.0, []any{0.0, 0.0, 0.0})
	tf(math_NegZero(), 0.0, []any{math_NegZero(), 0.0, 0.0})
	tf(math_NegZero(), 0.0, []any{0.0, math_NegZero(), 0.0})
	tf(math_NegZero(), 0.0, []any{0.0, 0.0, math_NegZero()})
	tf(math_NegZero(), 1.0, []any{1.0, 0.0, math_NegZero()})
	tf(-2.0, 0.0, []any{0.0, -1.0, math_NegZero(), -2.0})
	tf(-2.0, inf(1), []any{-2.0, -1.0, math_NegZero(), 0.0, inf(1)})
	tf(inf(-1), 0.0, []any{-2.0, 0.0, -1.0, inf(-1)})
	tf(inf(-1), inf(1), []any{inf(-1), -2.0, 0.0, -1.0, inf(1)})
	tf(inf(-1), inf(1), []any{inf(1), -2.0, 0.0, -1.0, inf(-1)})
	tf(inf(-1), inf(1), []any{inf(-1), -2.0, 0.0, New(inf(1))})

	tf(-2.0, 0.0, []any{-2.0, 0.0, -1.0})
	tf(-2.0, 0.0, []any{-2.0, -1.0, math_NegZero(), 0.0})
	tf(-2.0, 0.0, []any{0.0, -2.0, -1.0})
	tf(-2.0, 0.0, []any{0.0, -1.0, -2.0})
	tf(-2.0, 0.0, []any{-1.0, -2.0, 0.0})
	tf(-2.0, 0.0, []any{-1.0, 0.0, math_NegZero(), -2.0})

	tf(-1.0, 1.0, []any{-1.0, 0.0, 1.0})
	tf(-1.0, 1.0, []any{-1.0, 1.0, 0.0})
	tf(-1.0, 1.0, []any{0.0, -1.0, 1.0})
	tf(-1.0, 1.0, []any{0.0, 1.0, -1.0})
	tf(-1.0, 1.0, []any{1.0, -1.0, 0.0})
	tf(-1.0, 1.0, []any{1.0, 0.0, -1.0})

	tf(0.0, 2.0, []any{0.0, 1.0, 2.0})
	tf(0.0, 2.0, []any{0.0, 2.0, 1.0})
	tf(0.0, 2.0, []any{1.0, 0.0, 2.0})
	tf(0.0, 2.0, []any{1.0, 2.0, 0.0})
	tf(0.0, 2.0, []any{2.0, 1.0, 0.0})
	tf(0.0, 2.0, []any{2.0, 0.0, 1.0})

	tf(-1.0, 1.0, []any{"-1", 0.0, New(1)})
	tf(-1.0, 1.0, []any{"-1", New(1)})
	tf(-1.0, 1.0, []any{0.0, "-1", New(1)})
	tf(0.0, 1.0, []any{0.0, New(1)})
	tf(1.0, 1.0, []any{New(1)})
	tf(-1.0, -1.0, []any{New(-1)})

	tf(0.0009999, 0.0010001, []any{0.001, 0.0009999, 0.0010001})
	tf(-0.0010001, -0.0009999, []any{-0.001, -0.0009999, -0.0010001})
	tf(-0.000001, 999.001, []any{2.0, math_NegZero(), "1e-9000000000000000", 324.32423423, -0.000001, "999.001", 10.0})
	tf("-9.99999e+9000000000000000", inf(1), []any{10.0, "-9.99999e+9000000000000000", New(inf(1)), "9.99999e+9000000000000000", 0.0})
	tf("-9.999999e+9000000000000000", "1.01e+9000000000000000", []any{"-9.99998e+9000000000000000", "-9.999999e+9000000000000000", "9e+8999999999999999", "1.01e+9000000000000000", 1e+300})
	tf(1.0, inf(1), []any{1.0, "1e+9000000000000001", 1e200})
	tf(inf(-1), 1.0, []any{1.0, "-1e+9000000000000001", -1e200})
	tf(0.0, 1.0, []any{1.0, "1e-9000000000000001", 1e-200})
	tf(math_NegZero(), 1.0, []any{1.0, "-1e-9000000000000001", 1e-200})
	tf(-3.0, 3.0, []any{1.0, "2", 3.0, "-1", -2.0, "-3"})
}
