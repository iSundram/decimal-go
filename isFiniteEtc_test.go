package decimal

import "testing"

func TestIsFiniteEtc(t *testing.T) {
	setCfg(20, 4, -7, 21, 9e15, -9e15, 1, false)

	n := New(1.0)

	assert(t, n.IsFinite())
	assert(t, !n.IsNaN())
	assert(t, !n.IsNeg())
	assert(t, !n.IsZero())
	assert(t, n.IsInt())
	assert(t, n.Eq(n))
	assert(t, n.Eq(1.0))
	assert(t, n.Eq("1.0"))
	assert(t, n.Eq("1.00"))
	assert(t, n.Eq("1.000"))
	assert(t, n.Eq("1.0000"))
	assert(t, n.Eq("1.00000"))
	assert(t, n.Eq("1.000000"))
	assert(t, n.Eq(New(1)))
	assert(t, n.Eq("0x1"))
	assert(t, n.Eq("0o1"))
	assert(t, n.Eq("0b1"))
	assert(t, n.Gt(0.99999))
	assert(t, !n.Gte(1.1))
	assert(t, n.Lt(1.001))
	assert(t, n.Lte(2.0))
	assert(t, n.String() == n.ValueOf())

	n = New("-0.1")

	assert(t, n.IsFinite())
	assert(t, !n.IsNaN())
	assert(t, n.IsNeg())
	assert(t, !n.IsZero())
	assert(t, !n.IsInt())
	assert(t, !n.Eq(0.1))
	assert(t, !n.Gt(-0.1))
	assert(t, n.Gte(-1.0))
	assert(t, n.Lt(-0.01))
	assert(t, !n.Lte(-1.0))
	assert(t, n.String() == n.ValueOf())

	n = New(inf(1))

	assert(t, !n.IsFinite())
	assert(t, !n.IsNaN())
	assert(t, !n.IsNeg())
	assert(t, !n.IsZero())
	assert(t, !n.IsInt())
	assert(t, n.Eq("Infinity"))
	assert(t, n.Eq(inf(1)))
	assert(t, n.Gt("9e999"))
	assert(t, n.Gte(inf(1)))
	assert(t, !n.Lt(inf(1)))
	assert(t, n.Lte(inf(1)))
	assert(t, n.String() == n.ValueOf())

	n = New("-Infinity")

	assert(t, !n.IsFinite())
	assert(t, !n.IsNaN())
	assert(t, n.IsNeg())
	assert(t, !n.IsZero())
	assert(t, !n.IsInt())
	assert(t, !n.Eq(inf(1)))
	assert(t, n.Eq(inf(-1)))
	assert(t, !n.Gt(inf(-1)))
	assert(t, n.Gte("-Infinity"))
	assert(t, n.Lt(0.0))
	assert(t, n.Lte(inf(1)))
	assert(t, n.String() == n.ValueOf())

	n = New("0.0000000")

	assert(t, n.IsFinite())
	assert(t, !n.IsNaN())
	assert(t, !n.IsNeg())
	assert(t, n.IsZero())
	assert(t, n.IsInt())
	assert(t, n.Eq(math_NegZero()))
	assert(t, n.Gt(-0.000001))
	assert(t, !n.Gte(0.1))
	assert(t, n.Lt(0.0001))
	assert(t, n.Lte(math_NegZero()))
	assert(t, n.String() == n.ValueOf())

	n = New(math_NegZero())

	assert(t, n.IsFinite())
	assert(t, !n.IsNaN())
	assert(t, n.IsNeg())
	assert(t, n.IsZero())
	assert(t, n.IsInt())
	assert(t, n.Eq("0.000"))
	assert(t, n.Gt(-1.0))
	assert(t, !n.Gte(0.1))
	assert(t, !n.Lt(0.0))
	assert(t, !n.Lt(0.0))
	assert(t, n.Lt(0.1))
	assert(t, n.Lte(0.0))
	assert(t, n.ValueOf() == "-0" && n.String() == "0")

	n = New("NaN")

	assert(t, !n.IsFinite())
	assert(t, n.IsNaN())
	assert(t, !n.IsNeg())
	assert(t, !n.IsZero())
	assert(t, !n.IsInt())
	assert(t, !n.Eq(nan()))
	assert(t, !n.Eq(inf(1)))
	assert(t, !n.Gt(0.0))
	assert(t, !n.Gte(0.0))
	assert(t, !n.Lt(1.0))
	assert(t, !n.Lte(math_NegZero()))
	assert(t, !n.Lte(-1.0))
	assert(t, n.String() == n.ValueOf())

	n = New("-1.234e+2")

	assert(t, n.IsFinite())
	assert(t, !n.IsNaN())
	assert(t, n.IsNeg())
	assert(t, !n.IsZero())
	assert(t, !n.IsInt())
	assert(t, n.Eq(-123.4))
	assert(t, n.Gt("-0xff"))
	assert(t, n.Gte("-1.234e+3"))
	assert(t, n.Lt(-123.39999))
	assert(t, n.Lte("-123.4e+0"))
	assert(t, n.String() == n.ValueOf())

	n = New("5e-200")

	assert(t, n.IsFinite())
	assert(t, !n.IsNaN())
	assert(t, !n.IsNeg())
	assert(t, !n.IsZero())
	assert(t, !n.IsInt())
	assert(t, n.Eq(5e-200))
	assert(t, n.Gt(5e-201))
	assert(t, !n.Gte(1.0))
	assert(t, n.Lt(6e-200))
	assert(t, n.Lte(5.1e-200))
	assert(t, n.String() == n.ValueOf())

	n = New("1")

	assert(t, n.Eq(n))
	assert(t, n.Eq(n.String()))
	assert(t, n.Eq(n.String()))
	assert(t, n.Eq(n.ValueOf()))
	assert(t, n.Eq(n.ToFixed()))
	assert(t, n.Eq(1.0))
	assert(t, n.Eq("1e+0"))
	assert(t, !n.Eq(-1.0))
	assert(t, !n.Eq(0.1))

	assert(t, !New(nan()).Eq(0.0))
	assert(t, !New(inf(1)).Eq(0.0))
	assert(t, !New(0.1).Eq(0.0))
	assert(t, !New(1e9+1).Eq(1e9))
	assert(t, !New(1e9-1).Eq(1e9))
	assert(t, New(1e9+1).Eq(1e9+1))
	assert(t, New(1.0).Eq(1.0))
	assert(t, !New(1.0).Eq(-1.0))
	assert(t, !New(nan()).Eq(nan()))
	assert(t, !New("NaN").Eq("NaN"))

	assert(t, !New(nan()).Gt(nan()))
	assert(t, !New(nan()).Lt(nan()))
	assert(t, New("0xa").Lte("0xff"))
	assert(t, New("0xb").Gte("0x9"))

	assert(t, !New(10.0).Gt(10.0))
	assert(t, !New(10.0).Lt(10.0))
	assert(t, !New(nan()).Lt(nan()))
	assert(t, !New(inf(1)).Lt(inf(-1)))
	assert(t, !New(inf(1)).Lt(inf(1)))
	assert(t, New(inf(1)).Lte(inf(1)))
	assert(t, !New(nan()).Gte(nan()))
	assert(t, New(inf(1)).Gte(inf(1)))
	assert(t, New(inf(1)).Gte(inf(-1)))
	assert(t, !New(nan()).Gte(inf(-1)))
	assert(t, New(inf(-1)).Gte(inf(-1)))

	assert(t, !New(2.0).Gt(10.0))
	assert(t, !New(10.0).Lt(2.0))
	assert(t, New(255.0).Lte("0xff"))
	assert(t, New("0xa").Gte("0x9"))
	assert(t, !New(0.0).Lte("NaN"))
	assert(t, !New(0.0).Gte(nan()))
	assert(t, !New(nan()).Lte("NaN"))
	assert(t, !New(nan()).Gte(nan()))
	assert(t, !New(0.0).Lte(inf(-1)))
	assert(t, New(0.0).Gte(inf(-1)))
	assert(t, New(0.0).Lte("Infinity"))
	assert(t, !New(0.0).Gte("Infinity"))
	assert(t, New(10.0).Lte(20.0))
	assert(t, !New(10.0).Gte(20.0))

	assert(t, !New(1.23001e-2).Lt(1.23e-2))
	assert(t, New(1.23e-2).Lt(1.23001e-2))
	assert(t, !New(1e-2).Lt(9.999999e-3))
	assert(t, New(9.999999e-3).Lt(1e-2))

	assert(t, !New(1.23001e+2).Lt(1.23e+2))
	assert(t, New(1.23e+2).Lt(1.23001e+2))
	assert(t, New(9.999999e+2).Lt(1e+3))
	assert(t, !New(1e+3).Lt(9.9999999e+2))

	assert(t, !New(1.23001e-2).Lte(1.23e-2))
	assert(t, New(1.23e-2).Lte(1.23001e-2))
	assert(t, !New(1e-2).Lte(9.999999e-3))
	assert(t, New(9.999999e-3).Lte(1e-2))

	assert(t, !New(1.23001e+2).Lte(1.23e+2))
	assert(t, New(1.23e+2).Lte(1.23001e+2))
	assert(t, New(9.999999e+2).Lte(1e+3))
	assert(t, !New(1e+3).Lte(9.9999999e+2))

	assert(t, New(1.23001e-2).Gt(1.23e-2))
	assert(t, !New(1.23e-2).Gt(1.23001e-2))
	assert(t, New(1e-2).Gt(9.999999e-3))
	assert(t, !New(9.999999e-3).Gt(1e-2))

	assert(t, New(1.23001e+2).Gt(1.23e+2))
	assert(t, !New(1.23e+2).Gt(1.23001e+2))
	assert(t, !New(9.999999e+2).Gt(1e+3))
	assert(t, New(1e+3).Gt(9.9999999e+2))

	assert(t, New(1.23001e-2).Gte(1.23e-2))
	assert(t, !New(1.23e-2).Gte(1.23001e-2))
	assert(t, New(1e-2).Gte(9.999999e-3))
	assert(t, !New(9.999999e-3).Gte(1e-2))

	assert(t, New(1.23001e+2).Gte(1.23e+2))
	assert(t, !New(1.23e+2).Gte(1.23001e+2))
	assert(t, !New(9.999999e+2).Gte(1e+3))
	assert(t, New(1e+3).Gte(9.9999999e+2))

	assert(t, !New("1.0000000000000000000001").IsInt())
	assert(t, !New("0.999999999999999999999").IsInt())
	assert(t, New("4e4").IsInt())
	assert(t, New("-4e4").IsInt())

	// Decimal.isDecimal

	assert(t, IsDecimal(New(1)))
	assert(t, IsDecimal(New("-2.3")))
	assert(t, IsDecimal(New(nan())))
	assert(t, IsDecimal(New("Infinity")))

	assert(t, !IsDecimal(nil))
	assert(t, !IsDecimal(0.0))
	assert(t, !IsDecimal(1.0))
	assert(t, !IsDecimal("-2.3"))
	assert(t, !IsDecimal(nan()))
	assert(t, !IsDecimal(inf(1)))
	assert(t, !IsDecimal(nil))
	assert(t, !IsDecimal(struct{}{}))
	assert(t, !IsDecimal(map[string]bool{"isDecimal": true}))
	type jsNumber float64
	assert(t, !IsDecimal(jsNumber(4)))
}
