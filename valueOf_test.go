package decimal

import "testing"

func TestValueOf(t *testing.T) {
	tf := func(expected string, n any) {
		t.Helper()
		assertEq(t, expected, New(n).ValueOf())
	}

	setCfg(20, 4, -9e15, 9e15, 9e15, -9e15, 1, false)

	tf("0", 0.0)
	tf("0", "0")
	tf("NaN", nan())
	tf("NaN", "NaN")
	tf("Infinity", inf(1))
	tf("Infinity", "Infinity")
	tf("1", 1.0)
	tf("9", 9.0)
	tf("90", 90.0)
	tf("90.12", 90.12)
	tf("0.1", 0.1)
	tf("0.01", 0.01)
	tf("0.0123", 0.0123)
	tf("111111111111111111111", "111111111111111111111")
	tf("0.00001", 0.00001)

	tf("-0", math_NegZero())
	tf("-0", "-0")
	tf("-Infinity", inf(-1))
	tf("-Infinity", "-Infinity")
	tf("-1", -1.0)
	tf("-9", -9.0)
	tf("-90", -90.0)
	tf("-90.12", -90.12)
	tf("-0.1", -0.1)
	tf("-0.01", -0.01)
	tf("-0.0123", -0.0123)
	tf("-111111111111111111111", "-111111111111111111111")
	tf("-0.00001", -0.00001)

	// Exponential format
	Default.ToExpNeg = 0
	Default.ToExpPos = 0

	tf("1e-7", 0.0000001)
	tf("1.23e-7", 0.000000123)
	tf("1.2e-8", 0.000000012)
	tf("-1e-7", -0.0000001)
	tf("-1.23e-7", -0.000000123)
	tf("-1.2e-8", -0.000000012)

	tf("5.73447902457635174479825134e+14", "573447902457635.174479825134")
	tf("1.07688e+1", "10.7688")
	tf("3.171194102379077141557759899307946350455841e+27", "3171194102379077141557759899.307946350455841")
	tf("4.924353466898191177698653319742594890634579e+37", "49243534668981911776986533197425948906.34579")
	tf("6.85558243926569397328633907445409866949445343654692955e+18", "6855582439265693973.28633907445409866949445343654692955")
	tf("1e+0", "1")
}
